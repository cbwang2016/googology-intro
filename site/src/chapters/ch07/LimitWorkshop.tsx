import { useEffect, useRef, useState } from 'react'
import { L } from '../../i18n'
import { M } from '../../math'
import './limits.css'

type Kind = 'epsilon' | 'zeta' | 'eta' | 'gamma' | 'svo' | 'lvo' | 'bho' | 'bo'
const recipes: Record<Kind, { name: string; limit: string; rule: string; fixed?: string; seed: string; apply: (s: string, n: number) => string }> = {
  epsilon: { name: 'ε₀', limit: '\\varepsilon_0', rule: 'a_{k+1}=\\omega^{a_k}', fixed: '\\omega^{\\varepsilon_0}=\\varepsilon_0', seed: '1', apply: s => s === '1' ? '\\omega' : `\\omega^{${s}}` },
  zeta: { name: 'ζ₀', limit: '\\zeta_0', rule: 'a_{k+1}=\\varepsilon_{a_k}', fixed: '\\varepsilon_{\\zeta_0}=\\zeta_0', seed: '0', apply: s => `\\varepsilon_{${s}}` },
  eta: { name: 'η₀', limit: '\\eta_0', rule: 'a_{k+1}=\\zeta_{a_k}', fixed: '\\zeta_{\\eta_0}=\\eta_0', seed: '0', apply: s => `\\zeta_{${s}}` },
  gamma: { name: 'Γ₀ · Feferman–Schütte', limit: '\\Gamma_0', rule: 'a_{k+1}=\\varphi(a_k,0)', fixed: '\\varphi(\\Gamma_0,0)=\\Gamma_0', seed: '0', apply: s => s === '0' ? '1' : s === '1' ? '\\varepsilon_0' : `\\varphi(${s},0)` },
  svo: { name: 'SVO · Small Veblen', limit: '\\mathrm{SVO}', rule: 'a_k=\\varphi(1@k)', seed: '\\varphi(1)', apply: (_, n) => `\\varphi(1${',0'.repeat(n)})` },
  lvo: { name: 'LVO · Large Veblen', limit: '\\mathrm{LVO}', rule: 'a_{k+1}=\\varphi(1@a_k)', fixed: '\\varphi(1@\\mathrm{LVO})=\\mathrm{LVO}', seed: '0', apply: s => `\\varphi(1@${s})` },
  bho: { name: 'BHO · Bachmann–Howard', limit: '\\mathrm{BHO}', rule: 't_0=\\Omega,\\quad t_{k+1}=\\Omega^{t_k},\\quad a_k=\\psi(t_k)', seed: '\\psi(\\Omega)', apply: (_, n) => { let s = '\\Omega'; for (let i = 0; i < n; i++) s = `\\Omega^{${s}}`; return `\\psi(${s})` } },
  bo: { name: 'BO · Buchholz', limit: '\\mathrm{BO}', rule: 'a_k=\\psi(\\Omega_{k+1})', seed: '\\psi(\\Omega_1)', apply: (_, n) => `\\psi(\\Omega_{${n + 1}})` },
}

/** Finite terms are generated by the displayed recurrence. The supremum is a separate mathematical operation. */
export function LimitWorkshop({ kind }: { kind: Kind }) {
  const r = recipes[kind]
  const [step, setStep] = useState(0)
  const [playing, setPlaying] = useState(false)
  const [limit, setLimit] = useState(false)
  const root = useRef<HTMLDivElement>(null)
  const terms = [r.seed]
  for (let i = 1; i <= 5; i++) terms.push(r.apply(terms[i - 1], i))
  useEffect(() => {
    if (!playing) return
    const timer = window.setInterval(() => {
      if (!root.current?.getClientRects().length || document.hidden) { setPlaying(false); return }
      setStep(n => Math.min(5, n + 1))
    }, 1300)
    return () => window.clearInterval(timer)
  }, [playing])
  useEffect(() => { if (step === 5) setPlaying(false) }, [step])
  return <div ref={root} className="c07-limit-lab">
    <div className="c07-limit-rule"><L en="Construction" zh="构造规则" /> · <M t={r.rule} /></div>
    <div className="c07-limit-transfer" aria-live="polite" key={`${step}-${limit}`}>
      <span><L en="Current term" zh="当前项" /><br /><M t={`a_{${step}}=${terms[step]}`} /></span>
      <span className="c07-limit-arrow">→</span>
      <span><L en="Next term" zh="下一项" /><br /><M t={step < 5 ? `a_{${step + 1}}=${terms[step + 1]}` : r.rule} /></span>
    </div>
    <div className="c07-limit-trail" aria-label="Sequence">
      {terms.slice(0, 4).map((term, i) => <span key={i} className={i <= step ? 'reached' : ''}><M t={term} />{i < 3 && ' < '}</span>)}<span> &lt; ⋯</span>
    </div>
    <div className="btn-row">
      <button className="btn" disabled={step === 5} onClick={() => { setLimit(false); setPlaying(!playing) }}><L en={playing ? 'Pause' : 'Play'} zh={playing ? '暂停' : '播放'} /></button>
      <button className="btn" disabled={step === 5} onClick={() => { setPlaying(false); setStep(step + 1); setLimit(false) }}><L en="One step" zh="走一步" /></button>
      <button className="btn" onClick={() => { setPlaying(false); setLimit(!limit) }}><L en="Take the supremum" zh="取上确界" /></button>
      <button className="btn small" onClick={() => { setPlaying(false); setStep(0); setLimit(false) }}><L en="Reset" zh="重来" /></button>
    </div>
    <div className="c07-limit-destination" aria-live="polite">
      <b>{r.name}</b>
      {limit ? <><M t={`${r.limit}=\\sup_{k<\\omega}a_k`} />{r.fixed && <M t={r.fixed} />}</> : <M t={`a_{${step}}<${r.limit}`} />}
      <L en={limit ? 'The least upper bound of ALL terms, not a final animation frame.' : 'Every finite step stays below this milestone. The dots mean the rule continues without end.'} zh={limit ? '这是所有项的最小上界，不是动画最后一帧算出来的一项。' : '每个有限步骤都在这座里程碑之下。省略号表示规则一直继续。'} />
    </div>
  </div>
}
